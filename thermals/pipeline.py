WEATHER_SOURCE_TAG = "noaa_hrrr_herbie"


def _get_r2_client():
    bucket = os.environ.get("METEO_R2_BUCKET", "").strip()
    endpoint = (os.environ.get("R2_ENDPOINT") or os.environ.get("METEO_S3_ENDPOINT") or "").strip()
    access_key = (os.environ.get("R2_ACCESS_KEY_ID") or os.environ.get("AWS_ACCESS_KEY_ID") or "").strip()
    secret_key = (os.environ.get("R2_SECRET_ACCESS_KEY") or os.environ.get("AWS_SECRET_ACCESS_KEY") or "").strip()
    if not (bucket and endpoint and access_key and secret_key):
        return None, None
    import boto3
    from botocore.config import Config as BotoConfig

    s3 = boto3.client(
        "s3",
        endpoint_url=endpoint,
        aws_access_key_id=access_key,
        aws_secret_access_key=secret_key,
        region_name="auto",
        config=BotoConfig(signature_version="s3v4"),
    )
    return s3, bucket


def load_previous_cached_payload(cache_file: Path = FORECAST_CACHE_FILE) -> dict | None:
    """
    Loads the previous `thermal_predictions.json` from R2 (if configured) or local cache.
    Only returns payloads generated by real NOAA HRRR (`weather_source == 'noaa_hrrr_herbie'`).
    """
    s3, bucket = _get_r2_client()
    if s3 and bucket:
        try:
            logging.info(f"Checking R2 bucket '{bucket}' for existing {R2_FORECAST_KEY}...")
            resp = s3.get_object(Bucket=bucket, Key=R2_FORECAST_KEY)
            body = resp["Body"].read().decode("utf-8")
            payload = json.loads(body)
            if payload.get("metadata", {}).get("weather_source") == WEATHER_SOURCE_TAG:
                logging.info("Loaded previous real-HRRR forecast cache from R2.")
                return payload
            logging.info("Existing R2 payload is not marked as real-HRRR; will build fresh.")
        except Exception as e:
            logging.info(f"No prior real-HRRR cache loaded from R2 ({e}).")

    for candidate in (cache_file, METEOGRAMS_DEV_FORECAST_FILE):
        if candidate and candidate.exists():
            try:
                with open(candidate, "r") as f:
                    payload = json.load(f)
                if payload.get("metadata", {}).get("weather_source") == WEATHER_SOURCE_TAG:
                    logging.info(f"Loaded previous real-HRRR forecast cache from {candidate}.")
                    return payload
            except Exception as e:
                logging.warning(f"Failed to read local cache {candidate}: {e}")

    return None


def upload_payload_to_r2(payload_bytes: bytes) -> bool:
    s3, bucket = _get_r2_client()
    if not (s3 and bucket):
        return False
    s3.put_object(
        Bucket=bucket,
        Key=R2_FORECAST_KEY,
        Body=payload_bytes,
        ContentType="application/json",
        CacheControl="public, max-age=300",
    )
    logging.info(f"Uploaded {R2_FORECAST_KEY} ({len(payload_bytes) / 1024.0:.1f} KB) to R2 bucket '{bucket}'.")
    return True


def _compute_stats(probs: list[float], low_thresh: float, high_thresh: float) -> dict:
    arr = np.array(probs, dtype=float)
    high_count = int(np.sum(arr >= high_thresh))
    med_count = int(np.sum((arr >= low_thresh) & (arr < high_thresh)))
    low_count = int(np.sum(arr < low_thresh))
    total = max(1, len(arr))
    return {
        "mean_probability": round(float(np.mean(arr)), 3),
        "high_count": high_count,
        "high_pct": round(high_count / total * 100.0, 1),
        "med_count": med_count,
        "med_pct": round(med_count / total * 100.0, 1),
        "low_count": low_count,
        "low_pct": round(low_count / total * 100.0, 1),
    }


def compute_single_hour_output(
    fxx_idx: int,
    valid_local: datetime,
    terrain_cells: list[dict],
    fetcher: HRRRBoiseFetcher,
    predictor: ThermalPredictor,
    low_thresh: float = LOW_THRESHOLD,
    high_thresh: float = HIGH_THRESHOLD,
) -> dict:
    """
    Fetches HRRR meteorology for `valid_local` and runs LightGBM/XGBoost/Ensemble across all 690 cells.
    """
    hour_hrrr = fetcher.fetch_hour(valid_local)
    summary = hour_hrrr["summary"]
    cell_meteo_list = hour_hrrr["cell_features"]

    valid_utc = datetime.fromisoformat(summary["valid_utc"])
    solar_ctx = get_solar_context(valid_utc)
    is_daylight = solar_ctx["is_daylight"]

    rows = []
    cell_meta_list = []

    for c, c_met in zip(terrain_cells, cell_meteo_list):
        solar_inter = compute_solar_terrain_interactions(
            solar_ctx=solar_ctx,
            slope_deg=c["mean_slope"],
            aspect_deg=c["mean_aspect"],
            south_facing_fraction=c["south_facing_fraction"],
            albedo=c["albedo"],
        )

        # Match training formula in data_preparation_pipeline_multiregion.py
        angle_diff_rad = math.radians(c["mean_aspect"] - c_met["wind_dir_deg"])
        effective_headwind = math.cos(angle_diff_rad) * c_met["wind_speed_ms"]
        elev_x_instability = c["elevation_delta"] * c_met["instability_1000"]

        feat_dict = {
            "TOL_8000": c_met["TOL_8000"],
            "TOL_1000": c_met["TOL_1000"],
            "u_wind_6500": c_met["u_wind_6500"],
            "u_wind_2000": c_met["u_wind_2000"],
            "v_wind_7000": c_met["v_wind_7000"],
            "v_wind_2000": c_met["v_wind_2000"],
            "temperature_8000": c_met["temperature_8000"],
            "temperature_2500": c_met["temperature_2500"],
            "pressure_10000": c_met["pressure_10000"],
            "pressure_2500": c_met["pressure_2500"],
            "env_lapse_rate_4000": c_met["env_lapse_rate_4000"],
            "env_lapse_rate_11000": c_met["env_lapse_rate_11000"],
            "instability_1000": c_met["instability_1000"],
            "instability_11000": c_met["instability_11000"],
            "dew_height_4000": c_met["dew_height_4000"],
            "inversion_layer_1000": c_met["inversion_layer_1000"],
            "blh_sfc": c_met["blh_sfc"],
            "cape_sfc": c_met["cape_sfc"],
            "cin_sfc": c_met["cin_sfc"],
            "d2m_subh": c_met["d2m_subh"],
            "fricv_sfc": c_met["fricv_sfc"],
            "fsr_sfc": c_met["fsr_sfc"],
            "ishf_sfc": c_met["ishf_sfc"],
            "lftx_sfc": c_met["lftx_sfc"],
            "gust_subh": c_met["gust_subh"],
            "orog_subh": c_met["orog_subh"],
            "full_net_radiation": c_met["full_net_radiation"],
            "diffuse_fraction": c_met["diffuse_fraction"],
            "effective_headwind": round(effective_headwind, 3),
            "hour_of_day": solar_ctx["hour_of_day"],
            "month": solar_ctx["month"],
            "hours_past_solar_noon": solar_ctx["hours_past_solar_noon"],
            "absorbed_radiation": solar_inter["absorbed_radiation"],
            "slope_x_solar": solar_inter["slope_x_solar"],
            "solar_x_south_facing": solar_inter["solar_x_south_facing"],
            "max_elevation": c["max_elevation"],
            "mean_aspect": c["mean_aspect"],
            "mean_slope": c["mean_slope"],
            "neighbor_max_elevation": c["neighbor_max_elevation"],
            "elevation_delta": c["elevation_delta"],
            "elev_x_instability": round(elev_x_instability, 2),
            "south_facing_fraction": c["south_facing_fraction"],
        }

        rows.append(feat_dict)
        cell_meta_list.append({
            "id": c["id"],
            "lat": c["lat"],
            "lon": c["lon"],
            "elevation": c["elevation"],
            "mean_slope": c["mean_slope"],
            "mean_aspect": c["mean_aspect"],
            "zone": c["zone"],
            "absorbed_radiation": solar_inter["absorbed_radiation"],
        })

    df_feat = pd.DataFrame(rows)
    predictions = predictor.predict_dataframe(df_feat, low_thresh, high_thresh)

    hour_cells = []
    lgb_probs, xgb_probs, ens_probs = [], [], []

    for meta_c, pred in zip(cell_meta_list, predictions):
        if not is_daylight:
            for m_key in ("lightgbm", "xgboost", "ensemble"):
                pred[m_key]["probability"] = 0.05
                pred[m_key]["percentage"] = 5.0
                pred[m_key]["level"] = "low"
                pred[m_key]["label"] = "Low (Sun Below Horizon)"
                pred[m_key]["color"] = "#ef4444"

        hour_cells.append({
            **meta_c,
            "predictions": pred,
        })
        lgb_probs.append(pred["lightgbm"]["probability"])
        xgb_probs.append(pred["xgboost"]["probability"])
        ens_probs.append(pred["ensemble"]["probability"])

    return {
        "forecast_hour": fxx_idx,
        "hour_local": valid_local.hour,
        "valid_time_iso": summary["valid_local"],
        "local_time_display": summary["local_time_display"],
        "local_date_display": summary["local_date_display"],
        "is_daylight": is_daylight,
        "sun_elevation_deg": summary["sun_elevation_deg"],
        "weather_summary": {
            "temp_c": summary["t2m_c"],
            "temp_f": round(summary["t2m_c"] * 9.0 / 5.0 + 32.0, 1),
            "dew_c": summary["d2m_c"],
            "wind_speed_mph": summary["wind_speed_mph"],
            "wind_dir_deg": summary["wind_dir_deg"],
            "cape_jkg": summary["cape_sfc"],
            "blh_m": summary["blh_sfc"],
            "sensible_heat_wm2": summary["ishf_sfc"],
            "net_radiation_wm2": summary["full_net_radiation"],
        },
        "stats": {
            "lightgbm": _compute_stats(lgb_probs, low_thresh, high_thresh),
            "xgboost": _compute_stats(xgb_probs, low_thresh, high_thresh),
            "ensemble": _compute_stats(ens_probs, low_thresh, high_thresh),
        },
        "cells": hour_cells,
    }


def _extract_cached_hours_by_local_hour(day_block: dict | None) -> dict[int, dict]:
    if not day_block or not isinstance(day_block.get("forecast_hours"), list):
        return {}
    out: dict[int, dict] = {}
    for idx, item in enumerate(day_block["forecast_hours"]):
        if not isinstance(item, dict) or not isinstance(item.get("cells"), list) or len(item["cells"]) == 0:
            continue
        hr = int(item.get("hour_local", 8 + idx))
        out[hr] = item
    return out


def validate_payload(payload: dict, expected_cells: int = 690):
    for day_key in ("today", "yesterday"):
        hours = payload.get("forecast_days", {}).get(day_key, {}).get("forecast_hours", [])
        if len(hours) != len(DAYTIME_HOURS_LOCAL):
            raise ValueError(f"{day_key} has {len(hours)} hours; expected {len(DAYTIME_HOURS_LOCAL)}")
        for h in hours:
            cells = h.get("cells", [])
            if len(cells) != expected_cells:
                raise ValueError(f"{day_key} hour {h.get('hour_local')} has {len(cells)} cells; expected {expected_cells}")


def run_pipeline(
    now_utc: datetime | None = None,
    force_refresh: bool = False,
    cache_file: Path = FORECAST_CACHE_FILE,
    low_thresh: float = LOW_THRESHOLD,
    high_thresh: float = HIGH_THRESHOLD,
) -> dict:
    """
    Executes the hourly cached thermal forecast pipeline:
    1. Loads prior cached `thermal_predictions.json` (from R2 or local disk).
    2. Freezes all hours `< current_boise_hour` (and all of `yesterday`).
    3. Queries real NOAA HRRR via Herbie ONLY for hours `>= current_boise_hour` (or cold-start gaps).
    4. Writes updated JSON locally and to R2 only if every hour succeeds and validates.
    """
    t_start = time.time()
    DATA_DIR.mkdir(parents=True, exist_ok=True)

    if now_utc is None:
        now_utc = datetime.now(timezone.utc)
    elif now_utc.tzinfo is None:
        now_utc = now_utc.replace(tzinfo=timezone.utc)

    tz_boise = pytz.timezone(BOISE_TIMEZONE)
    now_local = now_utc.astimezone(tz_boise)
    yesterday_local = now_local - timedelta(days=1)

    today_iso = now_local.strftime("%Y-%m-%d")
    yesterday_iso = yesterday_local.strftime("%Y-%m-%d")
    current_hour_local = now_local.hour
    current_hour_iso = now_local.strftime("%Y-%m-%dT%H:00")

    logging.info(
        f"Starting Boise Thermal Pipeline for local time {now_local.strftime('%Y-%m-%d %H:%M %Z')} "
        f"(current_hour_local={current_hour_local})..."
    )

    terrain_cells = generate_terrain_grid(force_recompute=False)
    previous_payload = load_previous_cached_payload(cache_file=cache_file)
    run_time_utc = find_latest_available_hrrr_run(now_utc)

    if not force_refresh and previous_payload is not None:
        prev_meta = previous_payload.get("metadata", {})
        if (
            prev_meta.get("weather_source") == WEATHER_SOURCE_TAG
            and prev_meta.get("current_hour_iso") == current_hour_iso
            and prev_meta.get("run_timestamp_utc") == run_time_utc.isoformat()
        ):
            logging.info(
                f"Hourly cache already up to date for {current_hour_iso} and HRRR {run_time_utc.isoformat()}. "
                "Skipping recomputation."
            )
            return previous_payload

    # Resolve frozen cached hours for Yesterday and Today (< current_hour_local)
    frozen_yesterday_by_hour: dict[int, dict] = {}
    frozen_today_by_hour: dict[int, dict] = {}

    if previous_payload is not None:
        prev_meta = previous_payload.get("metadata", {})
        prev_days = previous_payload.get("forecast_days", {})
        prev_today_iso = prev_meta.get("today_date_iso")
        prev_yesterday_iso = prev_meta.get("yesterday_date_iso")

        if prev_today_iso == today_iso:
            frozen_today_by_hour = _extract_cached_hours_by_local_hour(prev_days.get("today"))
            if prev_yesterday_iso == yesterday_iso:
                frozen_yesterday_by_hour = _extract_cached_hours_by_local_hour(prev_days.get("yesterday"))
        elif prev_today_iso == yesterday_iso:
            # Midnight rollover: yesterday's completed `today` becomes `yesterday`
            logging.info(f"Rolling cached Today ({prev_today_iso}) into Yesterday ({yesterday_iso}).")
            frozen_yesterday_by_hour = _extract_cached_hours_by_local_hour(prev_days.get("today"))

    fetcher = HRRRBoiseFetcher(terrain_cells=terrain_cells, run_time_utc=run_time_utc)
    predictor = ThermalPredictor()

    try:
        # 1. Build Yesterday hours (100% frozen from cache when available; backfill only if missing on cold start)
        yesterday_hours_output = []
        for idx, hour_local in enumerate(DAYTIME_HOURS_LOCAL):
            if hour_local in frozen_yesterday_by_hour:
                cached_hr = dict(frozen_yesterday_by_hour[hour_local])
                cached_hr["forecast_hour"] = idx
                cached_hr["hour_local"] = hour_local
                yesterday_hours_output.append(cached_hr)
            else:
                valid_local = tz_boise.localize(
                    datetime(yesterday_local.year, yesterday_local.month, yesterday_local.day, hour_local, 0, 0)
                )
                logging.info(f"[Yesterday backfill] Computing missing past hour {hour_local:02d}:00...")
                hr_out = compute_single_hour_output(
                    fxx_idx=idx,
                    valid_local=valid_local,
                    terrain_cells=terrain_cells,
                    fetcher=fetcher,
                    predictor=predictor,
                    low_thresh=low_thresh,
                    high_thresh=high_thresh,
                )
                yesterday_hours_output.append(hr_out)

        # 2. Build Today hours: freeze `< current_hour_local` from cache; update `>= current_hour_local`
        today_hours_output = []
        frozen_count = 0
        updated_count = 0

        for idx, hour_local in enumerate(DAYTIME_HOURS_LOCAL):
            if hour_local < current_hour_local and hour_local in frozen_today_by_hour:
                cached_hr = dict(frozen_today_by_hour[hour_local])
                cached_hr["forecast_hour"] = idx
                cached_hr["hour_local"] = hour_local
                today_hours_output.append(cached_hr)
                frozen_count += 1
            else:
                valid_local = tz_boise.localize(
                    datetime(now_local.year, now_local.month, now_local.day, hour_local, 0, 0)
                )
                hr_out = compute_single_hour_output(
                    fxx_idx=idx,
                    valid_local=valid_local,
                    terrain_cells=terrain_cells,
                    fetcher=fetcher,
                    predictor=predictor,
                    low_thresh=low_thresh,
                    high_thresh=high_thresh,
                )
                today_hours_output.append(hr_out)
                updated_count += 1

        logging.info(
            f"Today hours built: {frozen_count} past hours kept frozen (< {current_hour_local:02d}:00), "
            f"{updated_count} hours updated from HRRR."
        )

        run_str = run_time_utc.strftime("%Y-%m-%d %H:00 UTC")
        retrieved_time_str = now_local.strftime("%b %-d, %Y at %-I:%M %p %Z")

        payload = {
            "metadata": {
                "weather_source": WEATHER_SOURCE_TAG,
                "model": "NOAA High-Resolution Rapid Refresh (HRRR)",
                "model_run": f"HRRR {run_str}",
                "run_timestamp_utc": run_time_utc.isoformat(),
                "current_hour_iso": current_hour_iso,
                "current_hour_local": current_hour_local,
                "retrieved_at_local": retrieved_time_str,
                "retrieved_at_utc": now_utc.isoformat(),
                "today_date_iso": today_iso,
                "today_date_display": now_local.strftime("%a, %b %-d"),
                "yesterday_date_iso": yesterday_iso,
                "yesterday_date_display": yesterday_local.strftime("%a, %b %-d"),
                "window_hours": "8:00 AM – 8:00 PM",
                "horizon_hours": len(DAYTIME_HOURS_LOCAL),
                "region": "Boise, Idaho",
                "bounds": {
                    "min_lat": min(c["lat"] for c in terrain_cells),
                    "max_lat": max(c["lat"] for c in terrain_cells),
                    "min_lon": min(c["lon"] for c in terrain_cells),
                    "max_lon": max(c["lon"] for c in terrain_cells),
                },
                "total_cells": len(terrain_cells),
                "models_available": ["ensemble", "lightgbm", "xgboost"],
                "thresholds": {"low": low_thresh, "high": high_thresh},
                "frozen_past_hours_count": frozen_count,
                "updated_hours_count": updated_count,
                "pipeline_runtime_sec": round(time.time() - t_start, 2),
            },
            "forecast_days": {
                "today": {
                    "key": "today",
                    "label": "Today",
                    "date_display": now_local.strftime("%a, %b %-d"),
                    "forecast_hours": today_hours_output,
                },
                "yesterday": {
                    "key": "yesterday",
                    "label": "Yesterday",
                    "date_display": yesterday_local.strftime("%a, %b %-d"),
                    "forecast_hours": yesterday_hours_output,
                },
            },
            "forecast_hours": today_hours_output,
        }

        validate_payload(payload, expected_cells=len(terrain_cells))
        payload_bytes = json.dumps(payload, separators=(",", ":")).encode("utf-8")

        cache_file.parent.mkdir(parents=True, exist_ok=True)
        with open(cache_file, "wb") as f:
            f.write(payload_bytes)
        logging.info(f"Saved validated forecast ({len(payload_bytes) / 1024.0:.1f} KB) to {cache_file}")

        if METEOGRAMS_DEV_DATA_DIR.exists():
            with open(METEOGRAMS_DEV_FORECAST_FILE, "wb") as f:
                f.write(payload_bytes)
            logging.info(f"Synced forecast to {METEOGRAMS_DEV_FORECAST_FILE}")

        upload_payload_to_r2(payload_bytes)
        return payload
    finally:
        fetcher.cleanup_cache()


def main():
    parser = argparse.ArgumentParser(description="Run Boise hourly NOAA HRRR thermal prediction pipeline.")
    parser.add_argument("--force", action="store_true", help="Force recomputation even if current hour is cached.")
    args = parser.parse_args()
    try:
        run_pipeline(force_refresh=args.force)
    except Exception as exc:
        logging.error(f"Pipeline failed; keeping previous published forecast untouched: {exc}", exc_info=True)
        sys.exit(1)


if __name__ == "__main__":
    main()
